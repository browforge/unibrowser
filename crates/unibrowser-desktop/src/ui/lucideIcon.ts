export function createLucideIcon(
  name: LucideName,
  sizePx = 16,
  className = "ub-icon",
): SVGSVGElement {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("xmlns", "http://www.w3.org/2000/svg");
  svg.setAttribute("width", String(sizePx));
  svg.setAttribute("height", String(sizePx));
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "1.75");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("class", className);
  svg.setAttribute("aria-hidden", "true");
  svg.dataset.lucide = name;
  svg.innerHTML = PATHS[name];
  return svg;
}

export function tabIconForKind(kind: string, isHttp: boolean, isDirectory: boolean): LucideName {
  if (isDirectory) {
    return "folder";
  }
  if (isHttp) {
    return "globe";
  }
  const k = kind.toLowerCase();
  if (k.includes("pdf") || k.includes("image")) {
    return k.includes("image") ? "image" : "file";
  }
  if (k.includes("text") || k.includes("markdown") || k.includes("plain")) {
    return "file-text";
  }
  if (k.includes("unibrow") || k.includes("project")) {
    return "file-code";
  }
  return "file";
}
